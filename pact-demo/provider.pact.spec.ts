//This test starts the real API, then asks Pact to replay the consumer's contract against it.

import { test, expect } from '@playwright/test';
import { Verifier } from '@pact-foundation/pact';
import path from 'node:path';
import { createLocationServer } from './location-provider';

test('real LocationService satisfies BookingService contract', async () => {
    test.setTimeout(60_000);
  const server = createLocationServer();

  // Start the real provider on an available local port.
  await new Promise<void>((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', () => resolve());
  });

  try {
    const address = server.address();

    if (!address || typeof address === 'string') {
      throw new Error('Could not determine provider server port');
    }

    const verifier = new Verifier({
      provider: 'LocationService',
      providerBaseUrl: `http://127.0.0.1:${address.port}`,

      // Read the contract generated by consumer.pact.spec.ts.
      pactUrls: [
        path.resolve(
          process.cwd(),
          'pacts/BookingService-LocationService.json',
        ),
      ],

      // Prepare the provider state required by the contract.
      // This demo's API has static data, so no database setup is needed.
      stateHandlers: {
        'location 123 exists': async () => {},
      },
    });

    // Send the contract's request to the real API and compare its response.
    const result = await verifier.verifyProvider();

    expect(result).toBeTruthy();
  } finally {
    // Always stop the local provider after verification.
    await new Promise<void>((resolve, reject) => {
      server.close((error) => error ? reject(error) : resolve());
    });
  }
});